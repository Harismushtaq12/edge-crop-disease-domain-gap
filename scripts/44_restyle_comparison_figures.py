"""
Restyles the three remaining per-intervention comparison figures (few-shot
fine-tuning, CutMix, ImageNet-pretrained) into the shared visual system.

All three answer the same two questions about one intervention -- what it
does to lab and field accuracy, and what it does to where the model looks --
so they are now generated by one function and share an identical layout,
axis range and colour assignment. That consistency is the point: a reader
comparing Fig. 11, 12 and 13 should be comparing the data, not re-learning
three different chart designs.

Produces:
  figures/mitigation_v2.png
  figures/cutmix_v2.png
  figures/pretrained_v2.png
"""
import json
import numpy as np
import figstyle as fs
import matplotlib.pyplot as plt

fs.apply()

sb = {v["label"]: v for v in json.load(open("unified_scoreboard.json"))["variants"]}


def acc_pair(label, field_key):
    v = sb[label]
    return v["lab"] * 100, v[field_key] * 100


def gradcam(path):
    d = json.load(open(path))
    return (d["all"]["mean_chance"] * 100, d["all"]["mean_energy_in_box"] * 100,
            d["n_scored"])


def two_panel(out, groups, gcam, field_label, title_a, title_b, note_b):
    """groups: list of (name, lab%, field%); gcam: list of (name, chance, energy)."""
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(fs.FULL_W, 2.7),
                                  gridspec_kw={"width_ratios": [1.25, 1.0]})

    x = np.arange(2)          # lab, field
    n = len(groups)
    w = 0.8 / n
    palette = [fs.C_BEFORE, fs.BLUE, fs.ORANGE, fs.AQUA][:n]
    for i, ((name, lab, fld), col) in enumerate(zip(groups, palette)):
        off = (i - (n - 1) / 2) * w
        b = ax.bar(x + off, [lab, fld], w * 0.9, color=col, label=name, zorder=3)
        fs.bar_labels(ax, b, fmt="{:.1f}", fontsize=fs.FS_ANNOT - 1.0)
    ax.axhline(12.5, color=fs.MUTED, lw=0.9, ls=(0, (4, 2.5)), zorder=2)
    ax.set_xticks(x)
    ax.set_xticklabels(["Lab\n(PlantVillage)", field_label])
    ax.set_ylabel("Top-1 accuracy (%)")
    ax.set_ylim(0, 112)
    fs.panel_title(ax, "a", title_a)
    ax.legend(loc="upper right", fontsize=fs.FS_LEGEND)
    fs.grid_y_only(ax)
    fs.tick_labels(ax)

    xg = np.arange(len(gcam))
    wg = 0.36
    ch = [c for _, c, _ in gcam]
    en = [e for _, _, e in gcam]
    b1 = ax2.bar(xg - wg / 2, ch, wg * 0.92, color=fs.C_CHANCE,
                 label="chance $C(x)$", zorder=3)
    b2 = ax2.bar(xg + wg / 2, en, wg * 0.92, color=fs.C_ATTN,
                 label="attention $E(x)$", zorder=3)
    fs.bar_labels(ax2, b1, fmt="{:.1f}", fontsize=fs.FS_ANNOT - 1.0)
    fs.bar_labels(ax2, b2, fmt="{:.1f}", fontsize=fs.FS_ANNOT - 1.0)
    ax2.set_xticks(xg)
    ax2.set_xticklabels([n for n, _, _ in gcam])
    ax2.set_ylabel("Mean fraction (%)")
    ax2.set_ylim(0, max(max(ch), max(en)) * 1.42)
    fs.panel_title(ax2, "b", title_b)
    ax2.legend(loc="upper center", fontsize=fs.FS_LEGEND, ncol=2)
    fs.grid_y_only(ax2)
    fs.tick_labels(ax2)

    fs.finish(fig, out)


# ---------------------------------------------- Fig 11: few-shot fine-tuning
two_panel(
    "figures/mitigation_v2.png",
    [("Before (baseline)", *acc_pair("From-scratch baseline", "field_fttest")),
     ("Full fine-tune", *acc_pair("+ full fine-tune", "field_fttest")),
     ("Head-only", *acc_pair("+ head-only fine-tune", "field_fttest")),
     ("L2-SP", *acc_pair("+ L2-SP fine-tune", "field_fttest"))],
    [("Baseline", *gradcam("gradcam_bbox_energy_results.json")[:2])],
    "Field\n($D_{ft\\text{-}test}$, n=584)",
    "Accuracy, lab vs. field",
    "Attention vs. chance",
    "attention barely above chance",
)

# --------------------------------------------------------- Fig 12: CutMix
b_ch, b_en, n_sc = gradcam("gradcam_bbox_energy_results.json")
c_ch, c_en, _ = gradcam("gradcam_bbox_energy_cutmix_results.json")
two_panel(
    "figures/cutmix_v2.png",
    [("Before (baseline)", *acc_pair("From-scratch baseline", "field_full")),
     ("CutMix", *acc_pair("+ CutMix", "field_full"))],
    [("Baseline", b_ch, b_en), ("CutMix", c_ch, c_en)],
    "Field\n(PlantDoc, n=744)",
    "Accuracy, lab vs. field",
    "Attention vs. chance",
    f"all {n_sc} scorable field images",
)

# ------------------------------------------------ Fig 13: ImageNet-pretrained
p_ch, p_en, _ = gradcam("gradcam_bbox_energy_pretrained_results.json")
two_panel(
    "figures/pretrained_v2.png",
    [("From-scratch", *acc_pair("From-scratch baseline", "field_full")),
     ("ImageNet-pretrained", *acc_pair("ImageNet-pretrained", "field_full"))],
    [("From-scratch", b_ch, b_en), ("Pretrained", p_ch, p_en)],
    "Field\n(PlantDoc, n=744)",
    "Accuracy, lab vs. field",
    "Attention vs. chance",
    f"all {n_sc} scorable field images",
)
